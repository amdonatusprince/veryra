#[near]
impl NonFungibleTokenCore for Veyra {
    #[payable]
    fn nft_transfer(
        &mut self,
        receiver_id: AccountId,
        token_id: TokenId,
        approval_id: Option<u64>,
        memo: Option<String>,
    ) {
        assert_one_yocto();
        self.must_membership(&token_id);
        let sender = env::predecessor_account_id();
        let (previous_owner, _) = self.tokens.internal_transfer(
            &sender,
            &receiver_id,
            &token_id,
            approval_id,
            memo.clone(),
        );
        self.after_transfer(&token_id, previous_owner, receiver_id, memo);
    }

    #[payable]
    fn nft_transfer_call(
        &mut self,
        receiver_id: AccountId,
        token_id: TokenId,
        approval_id: Option<u64>,
        memo: Option<String>,
        msg: String,
    ) -> PromiseOrValue<bool> {
        self.must_membership(&token_id);
        let previous_owner = self.owner_of(&token_id);
        let result = self.tokens.nft_transfer_call(
            receiver_id.clone(),
            token_id.clone(),
            approval_id,
            memo.clone(),
            msg,
        );
        self.after_transfer(&token_id, previous_owner, receiver_id, memo);
        result
    }

    fn nft_token(&self, token_id: TokenId) -> Option<Token> {
        self.tokens.nft_token(token_id)
    }
}

#[near]
impl NonFungibleTokenResolver for Veyra {
    #[private]
    fn nft_resolve_transfer(
        &mut self,
        previous_owner_id: AccountId,
        receiver_id: AccountId,
        token_id: TokenId,
        approved_account_ids: Option<HashMap<AccountId, u64>>,
    ) -> bool {
        let kept = self.tokens.nft_resolve_transfer(
            previous_owner_id,
            receiver_id,
            token_id.clone(),
            approved_account_ids,
        );
        if !kept {
            self.push_history(&token_id, "transfer_reverted", None, None, None, None);
        }
        kept
    }
}

